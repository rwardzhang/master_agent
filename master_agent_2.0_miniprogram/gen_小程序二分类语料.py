QUESTION_MARK = ("吗", "怎么", "多少", "哪儿", "哪里", "几", "多远", "多久", "贵不贵", "没")


def is_clean(q: str) -> bool:
    # 连续三个相同字符：品牌"一点点"+动作"点杯奶茶" → "一点点点杯奶茶"
    for i in range(len(q) - 2):
        if q[i] == q[i + 1] == q[i + 2]:
            return False
    for b in ["的的", "帮我帮我", "打开打开", "用用", "看看看", "一下一下",
              "麻烦麻烦", "给我给我", "我要我要", "个个", "啊啊", "然后然后"]:
        if b in q:
            return False
    # 非相邻隐性重复（读着啰嗦但非叠字）
    for w in ["充电", "停车", "加油", "外卖", "咖啡", "快递", "打开", "小程序", "看看",
              "故事", "儿歌", "直播", "短剧", "音乐", "天气", "保险", "文档", "车位",
              "账单", "评分", "奶茶", "电影", "球赛", "读书", "听书", "麻将", "斗地主"]:
        if q.count(w) >= 2:
            return False
    return 3 <= len(q) <= 40


def decorate(base, heads, k):
    """加口语前缀，跳过与句子结构冲突的组合。"""
    out = {base}
    for h in random.sample(heads, k=k):
        if not h:
            continue
        # 疑问句不接"麻烦/请/帮我/给我"
        if any(m in base for m in QUESTION_MARK) and h in ("麻烦", "请", "帮我", "给我"):
            continue
        # 第一/第二人称开头、疑问词开头不加前缀
        if base.startswith(("你", "我", "今天", "明天", "附近", "哪", "这", "珠穆", "光速",
                            "中国", "地球", "长城", "太阳", "一公里", "水的", "怎么", "车位")):
            continue
        q = h + base
        if is_clean(q):
            out.add(q)
    return out


