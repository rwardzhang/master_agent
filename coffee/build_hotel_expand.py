# ===== 校验：必须含预订动词 + 不含纯查询字眼 =====
def has_book_verb(q: str) -> bool:
    return any(v in q for v in BOOK_VERBS)

def has_search_blacklist(q: str) -> bool:
    return any(b in q for b in SEARCH_BLACKLIST)

bad = []
for cat, items in groups:
    for q in items:
        if not has_book_verb(q):
            bad.append(("缺预订动词", cat, q))
        if has_search_blacklist(q):
            bad.append(("含查询字眼", cat, q))
if bad:
    print("校验未通过：")
    for tag, cat, q in bad:
        print(f"  [{tag}] {cat}: {q}")
    raise SystemExit(1)

# ===== 去重保序 =====
seen = set()
rows = []
idx = 1
for cat, items in groups:
    for q in items:
        q = q.strip()
        if not q or q in seen:
            continue
        seen.add(q)
        rows.append((idx, cat, q, LABEL))
        idx += 1

