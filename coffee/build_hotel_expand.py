for col_idx, _ in enumerate(headers, start=1):
    c = ws.cell(row=1, column=col_idx)
    c.font = header_font
    c.fill = header_fill
    c.alignment = center

zebra = PatternFill("solid", fgColor="F2F2F2")
for r in rows:
    ws.append(r)
    row_no = ws.max_row
    if row_no % 2 == 0:
        for col_idx in range(1, len(headers) + 1):
            ws.cell(row=row_no, column=col_idx).fill = zebra
    ws.cell(row=row_no, column=1).alignment = center
    ws.cell(row=row_no, column=2).alignment = center
    ws.cell(row=row_no, column=3).alignment = left_wrap
    ws.cell(row=row_no, column=4).alignment = center

